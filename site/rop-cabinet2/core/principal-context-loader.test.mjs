import assert from 'node:assert/strict';
import {principalContextLoader} from './principal-context-loader.mjs';
const p={subjectId:"alice"},q={organizationId:"org",year:2026,rowIds:["r1"]};
const context={authenticated:true,subjectId:"alice",organizationId:"org",year:2026,rows:[{id:"r1",organizationId:"org",year:2026}],rateData:{},decisions:[]};
let calls=0,seen;
const loader=await principalContextLoader(p,async s=>(seen=s,true),async s=>(calls++,context));
assert.deepEqual(await loader(q),context);
assert.equal(seen.subjectId,"alice");
assert.equal(seen.permission,"rop:preview");
assert.equal(calls,1);
await assert.rejects(loader({...q,rowIds:["r1","r1"]}),/INVALID_SCOPE/);
await assert.rejects(loader({...q,organizationId:"bad space"}),/INVALID_SCOPE/);
const blocked=await principalContextLoader(p,async()=>false,async()=>{throw Error("SHOULD_NOT_LOAD")});
await assert.rejects(blocked(q),/ACCESS_DENIED/);
const wrong=await principalContextLoader(p,async()=>true,async()=>({...context,subjectId:"bob"}));
await assert.rejects(wrong(q),/CONTEXT_IDENTITY_CONFLICT/);
const wrongRow=await principalContextLoader(p,async()=>true,async()=>({...context,rows:[{...context.rows[0],id:"other"}]}));
await assert.rejects(wrongRow(q),/ROW_IDENTITY_CONFLICT/);
await assert.rejects(principalContextLoader(null,async()=>true,async()=>context),/SERVER_PRINCIPAL_CONTEXT_REQUIRED/);
const forged=await principalContextLoader(p,async s=>(seen=s,true),async()=>context);
await forged({...q,subjectId:"bob",massKg:"999999",serverEvidenceVerified:true});
assert.equal(seen.subjectId,"alice");
assert.equal(Object.hasOwn(seen,"massKg"),false);
console.log("11 principal context loader assertions passed");
