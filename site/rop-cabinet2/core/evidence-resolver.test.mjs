import assert from 'node:assert/strict';
import {resolveEvidenceManifest} from './evidence-resolver.mjs';
const e={id:"e1",kind:"mass-report",documentId:"d1",documentVersion:"v1",serverVerified:true,registryChecked:true};
const row={id:"r1",organizationId:"org",year:2026,productKey:"p",sourceReportId:"rep",evidence:[e]};
const input={organizationId:"org",year:2026,rows:[row]};
const good=async q=>({authoritative:true,registryChecked:true,organizationId:q.organizationId,year:q.year,rowId:q.rowId,documentId:q.documentId,documentVersion:q.documentVersion,kind:q.kind});
const ok=await resolveEvidenceManifest(input,good);
assert.equal(ok.status,"STAGING_MANIFEST");
assert.equal(ok.publicationAllowed,false);
assert.equal(ok.requiresServerReverification,true);
assert.equal(await resolveEvidenceManifest(input,null).then(x=>x.reason),"SERVER_CONTEXT_REQUIRED");
assert.equal((await resolveEvidenceManifest(input,async()=>({}))).reason,"SERVER_EVIDENCE_REJECTED");
assert.equal((await resolveEvidenceManifest(input,async q=>({...await good(q),documentVersion:"old"}))).reason,"SERVER_EVIDENCE_REJECTED");
assert.equal((await resolveEvidenceManifest(input,async q=>({...await good(q),organizationId:"other"}))).reason,"SERVER_EVIDENCE_REJECTED");
assert.equal((await resolveEvidenceManifest(input,async()=>{throw Error("offline")})).reason,"SERVER_RESOLVER_ERROR");
assert.equal((await resolveEvidenceManifest({...input,rows:[{...row,evidence:[e,e]}]},good)).reason,"EVIDENCE_REFERENCE_REQUIRED");
assert.equal((await resolveEvidenceManifest({...input,rows:[{...row,evidence:[{...e,documentId:"bad id"}]}]},good)).reason,"EVIDENCE_REFERENCE_REQUIRED");
let seen;await resolveEvidenceManifest(input,async q=>{seen=q;return good(q)});
assert.equal("serverVerified" in seen,false);
assert.equal("registryChecked" in seen,false);
assert.equal("documentContents" in seen,false);
console.log("12 server evidence boundary assertions passed");
