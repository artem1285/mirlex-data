import assert from 'node:assert/strict';
import {buildEvidenceManifest} from './evidence-manifest.mjs';
const e={id:"e1",kind:"mass-report",documentId:"doc1",documentVersion:"v1",organizationId:"org",year:2026,rowId:"r1",serverVerified:true,registryChecked:true};
const r={id:"r1",organizationId:"org",year:2026,productKey:"p1",sourceReportId:"report1",evidence:[e]};
const input={organizationId:"org",year:2026,rows:[r]};
const ok=buildEvidenceManifest(input);
assert.equal(ok.status,"STAGING_MANIFEST");
assert.equal(ok.requiresServerReverification,true);
assert.equal(ok.publicationAllowed,false);
assert.equal(ok.rows[0].evidence[0].documentVersion,"v1");
assert.equal(buildEvidenceManifest({...input,rows:[r,r]}).reason,"ROW_SCOPE_OR_SOURCE_REQUIRED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[e,e]}]}).reason,"EVIDENCE_VERIFICATION_OR_REUSE");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[{...e,year:2025}]}]}).status,"BLOCKED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[{...e,serverVerified:false}]}]}).status,"BLOCKED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[{...e,registryChecked:false}]}]}).status,"BLOCKED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,sourceReportId:""}]}).status,"BLOCKED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[{...e,rowId:"r2"}]}]}).status,"BLOCKED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[{...e,id:"bad id"}]}]}).status,"BLOCKED");
assert.equal(buildEvidenceManifest({...input,rows:[{...r,evidence:[]}]}).status,"BLOCKED");
console.log("13 evidence manifest assertions passed");
