import assert from 'node:assert/strict';
import {authorizedCabinetPreview} from './authorized-cabinet-preview.mjs';
const request={organizationId:"org",year:2026,rowIds:["r1"],subjectId:"forged"};
const principal={subjectId:"actual"};
let authCall=null,loadCalls=0;
const authorize=async q=>(authCall=q,true);
const load=async()=>{loadCalls++;return null;};
const resolve=async()=>null;
assert.equal((await authorizedCabinetPreview(request,null,authorize,load,resolve)).reason,"AUTHENTICATED_PRINCIPAL_REQUIRED");
assert.equal((await authorizedCabinetPreview(request,{subjectId:"bad space"},authorize,load,resolve)).reason,"AUTHENTICATED_PRINCIPAL_REQUIRED");
assert.equal((await authorizedCabinetPreview({...request,organizationId:"bad space"},principal,authorize,load,resolve)).reason,"SERVER_REQUEST_INVALID");
assert.equal((await authorizedCabinetPreview(request,principal,async()=>false,load,resolve)).reason,"ORGANIZATION_ACCESS_DENIED");
assert.equal((await authorizedCabinetPreview(request,principal,async()=>{throw Error("down")},load,resolve)).reason,"AUTHORIZATION_CHECK_ERROR");
assert.equal(loadCalls,0);
assert.equal((await authorizedCabinetPreview(request,principal,authorize,load,resolve)).reason,"SERVER_CONTEXT_REJECTED");
assert.equal(authCall.subjectId,"actual");
assert.equal(authCall.organizationId,"org");
assert.equal(authCall.permission,"rop:preview");
assert.equal(loadCalls,1);
console.log("10 authorization boundary assertions passed");
